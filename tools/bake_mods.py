def read_mod(jar: pathlib.Path) -> dict:
    """What a mod jar says about itself, and whether it needs mixins (which this cannot bake yet)."""
    with zipfile.ZipFile(jar) as archive:
        names = archive.namelist()
        descriptor = {}
        if "fabric.mod.json" in names:
            text = archive.read("fabric.mod.json").decode("utf-8", errors="replace")
            descriptor = json.loads(text)
        classes = [name for name in names if name.endswith(".class")]
        mixins = [name for name in names if "mixins" in name.lower() and name.endswith(".json")]
        mixin_classes = [name for name in classes if "mixin" in name.lower()]
    entrypoints = descriptor.get("entrypoints") or {}
    client = entrypoints.get("client") or entrypoints.get("main") or []
    entrypoint = None
    if client:
        first = client[0]
        entrypoint = str(first).split("::")[0] if isinstance(first, str) else None
    return {
        "file": jar.name,
        # A jar with no descriptor is not a mod: it is classes the mods need (the mixin callback stubs, for one).
        # It is copied into the client like any other jar, but it is not something to name on a loading screen.
        "is_library": "fabric.mod.json" not in names,
        "id": descriptor.get("id") or jar.stem,
        "name": descriptor.get("name") or descriptor.get("id") or jar.stem,
        "version": descriptor.get("version"),
        "entrypoint": entrypoint,
        "classes": len(classes),
        "mixin_configs": mixins,
        "mixin_classes": len(mixin_classes),
        "environment": descriptor.get("environment") or "both",
        "needs_mixins": bool(mixins) or len(mixin_classes) > 0,
    }



def remap_mods_to_official(mod_jars: list[pathlib.Path], official: pathlib.Path,
                           intermediary: pathlib.Path, out_dir: pathlib.Path, log=print) -> list[pathlib.Path]:
    """Rewrite mod jars from intermediary names to Mojang's official ones.

    A Fabric mod is compiled against intermediary names (`net/minecraft/class_2561`) because that is what
    Fabric Loader hands it at play time. A client compiled here has been remapped to Mojang's official names
    (`net/minecraft/network/chat/Component`), so a mod baked into it is full of references the compiler
    cannot resolve - the first build with Meteor died of exactly that, with "Class net.minecraft.class_2561
    was not found" and a gap report. Nothing bridged the two until this.

    The mapping is composed from the two files that already exist (Mojang's client.txt and Fabric's
    mappings.tiny); neither alone can do it.
    """
    if not official.is_file() or not intermediary.is_file():
        log(f"  ! mod remap skipped: {official} / {intermediary} missing")
        return mod_jars
    here = pathlib.Path(__file__).resolve().parent
    composed = out_dir / "int-to-official"
    out_dir.mkdir(parents=True, exist_ok=True)
    compose = subprocess.run([sys.executable, str(here / "compose_mappings.py"),
                              "--official", str(official), "--intermediary", str(intermediary),
                              "--out", str(composed)], capture_output=True, text=True)
    if compose.returncode != 0:
        log(f"  ! mod remap skipped, the mapping could not be composed: {compose.stderr.strip()[:200]}")
        return mod_jars
    log("  " + compose.stdout.strip().splitlines()[-1])
    asm = asm_classpath_for(here, os.environ.get("WEBMC_ASM"))
    if not asm:
        log("  ! mod remap skipped: no ASM jars")
        return mod_jars
    work = out_dir / "remapper"
    work.mkdir(parents=True, exist_ok=True)
    javac = subprocess.run(["javac", "--release", "17", "-nowarn", "-cp", asm, "-d", str(work),
                            str(here / "remap" / "ModRemapper.java")], capture_output=True, text=True)
    if javac.returncode != 0:
        log(f"  ! mod remap skipped, the remapper did not compile: {javac.stderr.strip()[:200]}")
        return mod_jars
    remapped = []
    for jar in mod_jars:
        target = out_dir / f"{jar.stem}-official.jar"
        run = subprocess.run(["java", "-cp", f"{work}{os.pathsep}{asm}", "ModRemapper",
                              str(jar), str(target), str(composed)], capture_output=True, text=True)
        if run.returncode != 0 or not target.is_file():
            log(f"  ! {jar.name}: could not be remapped, used as it was ({run.stderr.strip()[:120]})")
            remapped.append(jar)
            continue
        log("  " + run.stdout.strip().splitlines()[-1].replace(str(target), jar.name))
        remapped.append(target)
    return remapped


def asm_classpath_for(here: pathlib.Path, explicit: str | None = None) -> str:
    """The ASM jars: what the caller named, then the places a build actually stages them.

    /tmp/mods is where the build job puts them (it collects asm-*.jar from the engine for the bake), and
    that is the one that mattered: without it the remap was skipped with "no ASM jars" and the compiler
    then failed on the very references the remap removes.
    """
    if explicit:
        return explicit
    for directory in (here.parent / "work" / "asm",
                      pathlib.Path("/tmp/mods"),
                      pathlib.Path("work/asm"),
                      pathlib.Path.home() / ".m2" / "repository" / "org" / "ow2" / "asm"):
        if directory.is_dir():
            jars = [str(path) for path in sorted(directory.glob("*.jar"))]
            if jars:
                return os.pathsep.join(jars)
    return ""


def build_optional_stubs(mod_jars: list[pathlib.Path], engine: pathlib.Path, version: str,
                         prefixes: list[str], scan: pathlib.Path | None = None,
                         log=print) -> list[pathlib.Path]:
    """Shapes for the mods' optional dependencies, as a jar added to the set that gets baked.

    Meteor Client carries a Baritone integration, so its classes name baritone.api.IBaritone and friends.
    Fabric Loader tolerates a missing class until something touches it; a browser client is compiled whole
    and stops there ("Class baritone.api.IBaritone was not found"). The stubs are generated from the mods'
    own bytecode, compiled against the client, and handed to the rest of the pipeline as one more jar.
    """
    if not prefixes:
        return mod_jars
    here = pathlib.Path(__file__).resolve().parent
    client = engine / "port" / "work" / version / "client-named.jar"
    scan = scan or pathlib.Path("/tmp/mods")
    out = scan / "webmc-optional-stubs.jar"
    command = [sys.executable, str(here / "build_optional_stubs.py"),
               "--scan", str(scan), "--out", str(out)]
    for prefix in prefixes:
        command += ["--prefix", prefix]
    asm = asm_classpath_for(here, os.environ.get("WEBMC_ASM"))
    if asm:
        command += ["--asm", asm]
    if client.is_file():
        command += ["--client", str(client)]
    log(f"  optional dependencies: {', '.join(prefixes)} against {client.name}")
    result = subprocess.run(command, capture_output=True, text=True)
    for line in (result.stdout or "").strip().splitlines()[-6:]:
        log("  " + line)
    if result.returncode != 0 or not out.is_file():
        for line in (result.stderr or "").strip().splitlines()[-6:]:
            log("  ! " + line)
        log("  ! the stubs were not built; a mod that needs an absent dependency will not compile")
        return mod_jars
    log(f"  stubs built: {out.name} ({out.stat().st_size} bytes)")
    return sorted({*mod_jars, out})


def backport_client(engine: pathlib.Path, version: str, log=print) -> bool:
    """Read the client as Java 17, the way the compiler's class library expects.

    The client's own code returns java.util.SequencedSet where everything built against Fabric's
    intermediary says java.util.Set, and the compiler reports the method as missing rather than the type.
    tools/backport17.py already does this for the runtime JVM route; it needs the client and its libraries
    together, because it compiles shims for the client's own types.

    Runs in here rather than in the workflow because this output is certain to reach the build log: two
    runs died silently in a shell step whose later lines never produced a line of output.
    """
    here = pathlib.Path(__file__).resolve().parent
    work = pathlib.Path("/tmp/backport-work")
    client = engine / "port" / "work" / version / "client-named.jar"
    if not client.is_file():
        log("  ! no client-named.jar to backport")
        return False
    shutil.rmtree(work, ignore_errors=True)
    (work / "libs" / "client").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(client, work / "client-j17.jar")
    libraries = list((engine / "port" / "work" / version / "libraries").rglob("*.jar"))
    for library in libraries:
        try:
            shutil.copyfile(library, work / "libs" / "client" / library.name)
        except OSError:
            continue
    # the backport tool looks for ASM in work/asm, which a build machine does not have: it comes from the
    # engine, staged for the remap. Put them where the tool looks.
    asm = asm_classpath_for(here, os.environ.get("WEBMC_ASM"))
    if asm:
        target = pathlib.Path(__file__).resolve().parents[1] / "work" / "asm"
        target.mkdir(parents=True, exist_ok=True)
        for entry in asm.split(os.pathsep):
            source = pathlib.Path(entry)
            if source.is_file() and not (target / source.name).exists():
                try:
                    shutil.copyfile(source, target / source.name)
                except OSError:
                    continue
        copy = len(list(target.glob("*.jar")))
    log(f"  backporting the client to Java 17 ({len(libraries)} library jar(s) beside it, {copy} ASM jar(s) staged)")
    result = subprocess.run([sys.executable, str(here / "backport17.py"),
                             "--input", str(work / "client-j17.jar"),
                             "--output", str(work / "client-j17-out.jar")],
                            capture_output=True, text=True)
    for line in (result.stdout or "").strip().splitlines()[-4:]:
        log("  " + line)
    if result.returncode != 0 or not (work / "client-j17-out.jar").is_file():
        for line in (result.stderr or "").strip().splitlines()[-6:]:
            log("  ! " + line)
        log("  ! the client could not be backported; it is compiled as it is")
        return False
    shutil.copyfile(work / "client-j17-out.jar", client)
    log("  the client is backported to Java 17 for the compiler")
    return True


def bake(engine: pathlib.Path, version: str, mod_jars: list[pathlib.Path], mods_dir: pathlib.Path | None,
         log=print) -> dict:
    """Write the patcher, the hook and the shim, and add the patcher to the version profile."""
    mods = [read_mod(jar) for jar in mod_jars if jar.is_file()]
    if not mods:
        raise SystemExit("no mod jars to bake")
    for mod in mods:
        if mod.get("is_library"):
            continue  # the mixin stubs are a library: counting their class names as "mixins" is a false alarm
        if mod["needs_mixins"]:
            log(f"  {mod['id']} carries mixins ({len(mod['mixin_configs'])} config(s), "
                f"{mod['mixin_classes']} class(es) named like one): the applier merges them into the client "
                f"before it is compiled, and the build log says what it applied and what it refused")

    # the mod jars are copied into the engine, so the patcher finds them where the build runs
    shipped_dir = engine / "port" / "work" / version / "webmc-mods"
    shipped_dir.mkdir(parents=True, exist_ok=True)
    shipped = []
    for mod, jar in zip(mods, [jar for jar in mod_jars if jar.is_file()]):
        target = shipped_dir / jar.name
        # A jar may come from anywhere: the mods directory, or this repository's own build output (the mixin
        # stubs live in mods/jars/ and are built there). Preferring mods_dir without checking is how a build
        # failed on FileNotFoundError for a jar that was right there on disk.
        candidate = mods_dir / jar.name if mods_dir else None
        shutil.copyfile(candidate if candidate and candidate.is_file() else jar, target)
        shipped.append(str(target))
        mod["shipped"] = str(target)

    tools_dir = engine / "port" / "tools" / "src" / "main" / "java" / "dev" / "gaius" / "tools"
    if not tools_dir.is_dir():
        raise SystemExit(f"{engine} does not look like a profile-based engine: no {tools_dir}")
    applier_source = ROOT / "mods" / "mixin-applier" / "src" / "dev" / "gaius" / "tools" / "WebMcMixinApplier.java"
    if not applier_source.is_file():
        raise SystemExit(f"the mixin applier is missing: {applier_source}")
    applier_target = tools_dir / "WebMcMixinApplier.java"
    shutil.copyfile(applier_source, applier_target)
    log(f"  wrote {applier_target.relative_to(engine)} (the mixin applier the patcher calls)")

    patcher = tools_dir / f"{PATCHER_CLASS}.java"
    # a named placeholder rather than %-formatting: the template is Java, and one stray percent sign in
    # it becomes a compile error forty-five minutes into a build
    patcher.write_text(PATCHER_JAVA.replace("__CLASS__", PATCHER_CLASS))
    log(f"  wrote {patcher.relative_to(engine)}")

    overrides = engine / "port" / "overrides" / "client" / "src" / "versions" / version / "java"
    # Earlier bakes wrote a hook class here. It has to go: it was Java that named the mod's package, and the
    # engine compiles these sources before the patched classes are on its classpath.
    stale = overrides / "webmc" / "baked" / "WebMcBakedMods.java"
    if stale.is_file():
        stale.unlink()
        log(f"  removed {stale.relative_to(engine)} (superseded by bytecode injection)")
    libraries = [mod for mod in mods if mod.get("is_library")]
    if libraries:
        log("  " + str(len(libraries)) + " jar(s) are libraries rather than mods (no descriptor, nothing to call): "
            + ", ".join(mod["id"] for mod in libraries))
    if not any(mod.get("entrypoint") for mod in mods):
        log("  no client entrypoint in the mod set: the patcher will copy classes and call nothing")
    else:
        log("  each entrypoint is called from the client's static initialiser as bytecode")

    # Every shim, not one: a mod that calls the Fabric loader or the API needs those classes to exist
    # in the client the compiler sees, and the loader shims are what make `FabricLoader.getInstance()`
    # and a mod's own metadata work in a client that has no loader at play time.
    staged = []
    if SHIMS.is_dir():
        for source in sorted(SHIMS.rglob("*.java")):
            target = overrides / source.relative_to(SHIMS)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(source.read_text())
            staged.append(source.relative_to(SHIMS).as_posix())
    if staged:
        log(f"  staged {len(staged)} shim source file(s) the mods compile against "
            + f"({', '.join(staged[:3])}{'…' if len(staged) > 3 else ''})")

    # How the patcher gets called depends on which patch set the version is on, and the engine's own validator
    # decides that, not us: `extraPatchers` is refused outside the modern patch set ("extraPatchers is only
    # supported by the modern patch set"), and the 1.21 line is on a legacy chain. So:
    #   modern  -> the documented way, the profile lists the patcher
    #   legacy  -> a fixup appends it after the chain through build-overlays.sh, guarded by WEBMC_MOD_PATCHER,
    #              using the same run_client_patcher helper the chain itself uses
    profile_path = engine / "port" / "versions" / f"{version}.json"
    patch_set = ""
    if profile_path.is_file():
        profile = json.loads(profile_path.read_text())
        patch_set = str(profile.get("patchSet") or "")
    else:
        log(f"  ! no profile at {profile_path.relative_to(engine)}: if this version generates one, its patch set")
        log("    decides how the patcher is called, and until it exists only the chain hook can be used")
    modern = bool(patch_set) and not patch_set.startswith("legacy")
    if modern:
        profile["extraPatchers"] = [name for name in (profile.get("extraPatchers") or [])
                                    if name != PATCHER_CLASS] + [PATCHER_CLASS]
        profile_path.write_text(json.dumps(profile, indent=1) + "\n")
        patcher_env = ""
        route = "extraPatchers"
        log(f"  {profile_path.relative_to(engine)}: extraPatchers = {profile['extraPatchers']} "
            f"(patch set {patch_set})")
    else:
        patcher_env = f"WEBMC_MOD_PATCHER={PATCHER_CLASS}"
        route = "chain hook"
        log(f"  the patcher runs after the engine's chain (patch set {patch_set or 'unknown'}, "
            f"{patcher_env})")

    real = [mod for mod in mods if not mod.get("is_library")]
    return {
        "version": version,
        # what a page may name: the mods, not the libraries that came along with them
        "mod_ids": [mod["id"] for mod in real],
        "libraries": [mod["id"] for mod in libraries],
        "patcher": PATCHER_CLASS,
        "patcher_env": patcher_env,
        "patch_set": patch_set or None,
        "patcher_route": route,
        "mods": mods,
        "mod_jars": shipped,
        "webmc_mods": ":".join(shipped),
        "calls": [{"class": mod["entrypoint"], "id": mod["id"]} for mod in mods if mod.get("entrypoint")],
        "mixin_applier": str(applier_target.relative_to(engine)),
        "mods_with_mixins": [mod["id"] for mod in real if mod["needs_mixins"]],
        "with_mixins": [mod["id"] for mod in real if mod["needs_mixins"]],
        "entrypoints": [mod["id"] for mod in mods if mod["entrypoint"]],
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--mods", action="append", default=[], help="a mod jar (repeatable)")
    parser.add_argument("--mappings", default=None,
                        help="Mojang's client mappings for this version; with --intermediary, the mod jars "
                             "are remapped from intermediary to official names first, which is what the "
                             "compiler needs and what no previous build did")
    parser.add_argument("--asm", default=None,
                        help="a classpath of ASM jars for the remapper (the build stages them for the bake)")
    parser.add_argument("--mappings-intermediary", default=None,
                        help="Fabric's intermediary mapping file (mappings.tiny)")
    parser.add_argument("--mods-dir", default=None, help="where those jars came from")
    parser.add_argument("--report", default=None)
    parser.add_argument("--optional-stubs", default=None,
                        help="comma-separated package prefixes to generate stubs for (baritone), so a mod "
                             "that treats another mod as optional still compiles; also reads the client as "
                             "Java 17 first")
    parser.add_argument("--print", action="store_true")
    args = parser.parse_args(argv)

    if not args.mods:
        print("nothing to bake: pass --mods")
        return 2
    if args.optional_stubs:
        backport_client(pathlib.Path(args.engine), args.version)
    mod_jars = [pathlib.Path(p) for p in args.mods]
    mods_dir = pathlib.Path(args.mods_dir) if args.mods_dir else None
    if args.mappings:
        print("remapping the mod set to Mojang's official names, which is what the compiled client uses")
        official = pathlib.Path("/tmp/mods-official")
        if args.asm:
            os.environ["WEBMC_ASM"] = args.asm
        mod_jars = remap_mods_to_official(mod_jars, pathlib.Path(args.mappings),
                                          pathlib.Path(args.mappings_intermediary), official)
        # The bake also scans a mods directory, and that directory holds the *originals*: leaving it in
        # place baked both copies, which is exactly the failure the remap exists to prevent. The remapped
        # jars become the mods directory.
        staging = official / "mods"
        staging.mkdir(parents=True, exist_ok=True)
        for jar in mod_jars:
            target = staging / jar.name
            if jar.resolve() != target.resolve():
                shutil.copyfile(jar, target)
        mods_dir = staging
        mod_jars = sorted(staging.glob("*.jar"))
        print(f"  baking {len(mod_jars)} remapped jar(s) from {staging}")
        mod_jars = build_optional_stubs(mod_jars, pathlib.Path(args.engine), args.version,
                                       [p for p in args.optional_stubs.split(",") if p],
                                       scan=mods_dir)
    report = bake(pathlib.Path(args.engine), args.version, mod_jars, mods_dir)
    print(f"baked {len(report['mods'])} mod(s) into {args.version}: "
          f"entrypoints {', '.join(report['entrypoints']) or 'none'}"
          + (f"; mixins present in {', '.join(report['with_mixins'])} (not applied)" if report["with_mixins"] else ""))
    print(f"WEBMC_MODS={report['webmc_mods']}")
    if args.print:
        print(json.dumps(report, indent=1))
    if args.report:
        pathlib.Path(args.report).write_text(json.dumps(report, indent=1) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
