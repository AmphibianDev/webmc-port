#!/usr/bin/env python3
"""Bake a mod set into a profile-based engine, so a compiled 1.21.11 client has the mods inside it.

    python3 tools/bake_mods.py --engine work/engine --version 1.21.11 \\
        --mods mods/jars/hello-fabric.jar --mods-dir mods/jars --report /tmp/bake.json

Why a generator rather than a program: the engine's build already has a place to put code that runs
before the compile - its **patch chain**. A patcher is a Java class with `main(jar, classOutputDir,
version)` that reads a class out of the client jar, rewrites it with ASM, and writes the class file to a
directory the build merges over the client. So a mod set needs three things, and this tool writes all
three:

  1. **`WebMcModBakePatcher`** (a Java source in the engine's tools package): copies every class from the
     mod jars into the patch output, and injects one call - `webmc/baked/WebMcBakedMods.initialize()` -
     into the client's own startup method. The injected call is a symbolic reference; the class it names
     is compiled later, from step 2, into the same client.
  2. **`webmc/baked/WebMcBakedMods.java`** (a source override for this version): one line per mod that
     instantiates its client entrypoint and calls it, exactly the way Fabric Loader would at play time.
  3. **`net/fabricmc/api/ClientModInitializer.java`**: the interface a Fabric mod compiles against, taken
     from this repository's own shim (`mods/shims`), because a compiled client has no Fabric API present.

And it appends the patcher to the version profile's `extraPatchers`, which is the engine's own documented
way to have a per-version patcher run at the tail of its chain.

What this cannot do yet, and says so: **mixins**. A mod whose behaviour is mixins needs those transformed
into the client's source at build time, which is a different and larger job. A mod with an entrypoint and
no mixins works. The report names which mods fell into which group.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import shutil
import sys
import zipfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
SHIMS = ROOT / "mods" / "shims"

PATCHER_CLASS = "WebMcModBakePatcher"

PATCHER_JAVA = '''package dev.gaius.tools;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.AbstractInsnNode;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.InsnList;
import org.objectweb.asm.tree.MethodInsnNode;
import org.objectweb.asm.tree.MethodNode;

/**
 * WebMC's mod bake: put a Fabric mod's classes into the client and call its entrypoint.
 *
 * <p>Generated by tools/bake_mods.py. It runs at the tail of the engine's patch chain, so it sees the
 * client jar the other patchers produced, and everything it writes into the patch output directory is
 * merged over that jar before the client is decompiled and compiled.
 *
 * <p>Two things happen here:
 *
 * <ul>
 *   <li>every class from the mod jars is copied into the client - the mod is then part of the same
 *       compile, which is the only way a mod can exist in an ahead-of-time compiled client;</li>
 *   <li>{@code webmc/baked/WebMcBakedMods.initialize()} is called at the end of the client's own static
 *       initialiser, which runs once when the client class is first loaded - the closest thing to Fabric
 *       Loader's client entrypoint that a compiled client has.</li>
 * </ul>
 *
 * <p>The mod jars come from the {@code WEBMC_MODS} environment variable (a path-separated list), so this
 * class needs no knowledge of which mods are being baked.
 */
public final class __CLASS__ {

    /** The class this injects a call to; generated as a source override beside the client's sources. */
    private static final String HOOK = "webmc/baked/WebMcBakedMods";
    private static final String HOOK_METHOD = "initialize";
    private static final String HOOK_DESCRIPTOR = "()V";
    private static final String CLIENT = "net/minecraft/client/Minecraft.class";

    private __CLASS__() {
    }

    public static void main(String[] args) throws IOException {
        if (args.length < 2) {
            throw new IllegalArgumentException("usage: __CLASS__ <input.jar> <class-output-dir> [version]");
        }
        Path jar = Path.of(args[0]);
        Path output = Path.of(args[1]);
        Files.createDirectories(output);

        List<Path> mods = modJars();
        if (mods.isEmpty()) {
            System.out.println("__CLASS__: no mods in WEBMC_MODS, nothing baked");
            return;
        }

        int copied = 0;
        for (Path mod : mods) {
            copied += copyClasses(mod, output);
        }
        System.out.println("__CLASS__: copied " + copied + " class(es) from " + mods.size() + " mod jar(s)");

        byte[] input;
        try (ZipFile client = new ZipFile(jar.toFile())) {
            ZipEntry entry = client.getEntry(CLIENT);
            if (entry == null) {
                throw new IllegalStateException("the client jar has no " + CLIENT);
            }
            try (var stream = client.getInputStream(entry)) {
                input = stream.readAllBytes();
            }
        }

        ClassNode node = new ClassNode();
        new ClassReader(input).accept(node, 0);
        boolean injected = false;
        for (MethodNode method : node.methods) {
            if (!method.name.equals("<clinit>")) {
                continue;
            }
            // the end of the static initialiser, before its RETURN: the client class has been loaded,
            // and every class the mod needs is now real
            AbstractInsnNode last = method.instructions.getLast();
            method.instructions.insertBefore(last, call());
            injected = true;
            break;
        }
        if (!injected) {
            throw new IllegalStateException("net/minecraft/client/Minecraft has no static initialiser to "
                    + "call the baked mods from; this client's shape is not the one this patcher knows");
        }

        ClassWriter writer = new ClassWriter(0);
        node.accept(writer);
        Path target = output.resolve(CLIENT);
        Files.createDirectories(target.getParent());
        Files.write(target, writer.toByteArray());
        System.out.println("__CLASS__: injected " + HOOK + "." + HOOK_METHOD + " into the client's static initialiser");
    }

    private static InsnList call() {
        InsnList code = new InsnList();
        code.add(new MethodInsnNode(Opcodes.INVOKESTATIC, HOOK, HOOK_METHOD, HOOK_DESCRIPTOR, false));
        return code;
    }

    /** The mod jars the bake was asked for, from the environment so this class stays generic. */
    private static List<Path> modJars() {
        List<Path> found = new ArrayList<>();
        String list = System.getenv("WEBMC_MODS");
        if (list == null || list.isEmpty()) {
            return found;
        }
        for (String part : list.split(java.io.File.pathSeparator)) {
            if (part.trim().isEmpty()) {
                continue;
            }
            Path path = Path.of(part);
            if (Files.isRegularFile(path)) {
                found.add(path);
            } else {
                System.out.println("__CLASS__: ignoring " + path + " (not a file)");
            }
        }
        return found;
    }

    /** Copy every class of one mod into the client, and report what its descriptor says. */
    private static int copyClasses(Path mod, Path output) throws IOException {
        Map<String, String> descriptor = new LinkedHashMap<>();
        int copied = 0;
        try (ZipFile archive = new ZipFile(mod.toFile())) {
            ZipEntry manifest = archive.getEntry("fabric.mod.json");
            if (manifest != null) {
                try (var stream = archive.getInputStream(manifest)) {
                    String text = new String(stream.readAllBytes(), StandardCharsets.UTF_8);
                    descriptor.put("id", firstString(text, "id"));
                    descriptor.put("entrypoint", firstEntrypoint(text));
                }
            }
            var entries = archive.entries();
            while (entries.hasMoreElements()) {
                ZipEntry entry = entries.nextElement();
                if (entry.isDirectory() || !entry.getName().endsWith(".class")) {
                    continue;
                }
                Path target = output.resolve(entry.getName());
                Files.createDirectories(target.getParent());
                try (var stream = archive.getInputStream(entry)) {
                    Files.write(target, stream.readAllBytes());
                }
                copied += 1;
            }
        }
        System.out.println("__CLASS__: " + copied + " class(es) from " + mod.getFileName()
                + (descriptor.get("id") == null ? "" : " (id " + descriptor.get("id") + ")")
                + (descriptor.get("entrypoint") == null ? "" : ", entrypoint " + descriptor.get("entrypoint")));
        return copied;
    }

    /** The smallest possible reader for the two strings this needs out of a mod descriptor. */
    private static String firstString(String json, String key) {
        int at = json.indexOf("\\"" + key + "\\"");
        if (at < 0) {
            return null;
        }
        int colon = json.indexOf(':', at);
        int quote = json.indexOf('"', colon + 1);
        if (colon < 0 || quote < 0) {
            return null;
        }
        int end = json.indexOf('"', quote + 1);
        return end < 0 ? null : json.substring(quote + 1, end);
    }

    /** The client entrypoint's class name, out of an entrypoints block. */
    private static String firstEntrypoint(String json) {
        int at = json.indexOf("\\"client\\"");
        if (at < 0) {
            at = json.indexOf("\\"main\\"");
        }
        if (at < 0) {
            return null;
        }
        int open = json.indexOf('[', at);
        int quote = json.indexOf('"', open);
        if (open < 0 || quote < 0) {
            return null;
        }
        int end = json.indexOf('"', quote + 1);
        if (end < 0) {
            return null;
        }
        String value = json.substring(quote + 1, end);
        // "com.example.Hello::onInitializeClient" and "com.example.Hello" are both legal
        int separator = value.indexOf("::");
        return separator < 0 ? value : value.substring(0, separator);
    }
}
'''


def read_mod(jar: pathlib.Path) -> dict:
    """What a mod jar says about itself, and whether it needs mixins (which this cannot bake yet)."""
    with zipfile.ZipFile(jar) as archive:
        names = archive.namelist()
        descriptor = {}
        if "fabric.mod.json" in names:
            text = archive.read("fabric.mod.json").decode("utf-8", errors="replace")
            descriptor = json.loads(text)
        classes = [name for name in names if name.endswith(".class")]
        mixins = [name for name in names if "mixins" in name.lower() and name.endswith(".json")]
        mixin_classes = [name for name in classes if "mixin" in name.lower()]
    entrypoints = descriptor.get("entrypoints") or {}
    client = entrypoints.get("client") or entrypoints.get("main") or []
    entrypoint = None
    if client:
        first = client[0]
        entrypoint = str(first).split("::")[0] if isinstance(first, str) else None
    return {
        "file": jar.name,
        "id": descriptor.get("id") or jar.stem,
        "name": descriptor.get("name") or descriptor.get("id") or jar.stem,
        "version": descriptor.get("version"),
        "entrypoint": entrypoint,
        "classes": len(classes),
        "mixin_configs": mixins,
        "mixin_classes": len(mixin_classes),
        "environment": descriptor.get("environment") or "both",
        "needs_mixins": bool(mixins) or len(mixin_classes) > 0,
    }


def hook_source(mods: list[dict]) -> str:
    """The class the patcher calls: one instantiate-and-call per mod, as Fabric would do at play time."""
    lines = [
        "package webmc.baked;",
        "",
        "/**",
        " * The baked mod set's entrypoints.",
        " *",
        " * Written by tools/bake_mods.py. A compiled client has no class loader, so a mod cannot be started",
        " * the way Fabric Loader starts one; the engine's patch chain injects a call to this class into the",
        " * client's own static initialiser instead, and each line below is what Fabric Loader would have",
        " * done at play time.",
        " */",
        "public final class WebMcBakedMods {",
        "",
        "    private WebMcBakedMods() {",
        "    }",
        "",
        "    public static void initialize() {",
    ]
    for mod in mods:
        if not mod.get("entrypoint"):
            lines.append(f"        // {mod['id']}: no client entrypoint declared, so there is nothing to call")
            continue
        lines.append(f"        // {mod['name']} {mod.get('version') or ''}".rstrip())
        lines.append(f"        new {mod['entrypoint']}().onInitializeClient();")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def bake(engine: pathlib.Path, version: str, mod_jars: list[pathlib.Path], mods_dir: pathlib.Path | None,
         log=print) -> dict:
    """Write the patcher, the hook and the shim, and add the patcher to the version profile."""
    mods = [read_mod(jar) for jar in mod_jars if jar.is_file()]
    if not mods:
        raise SystemExit("no mod jars to bake")
    for mod in mods:
        if mod["needs_mixins"]:
            log(f"  ! {mod['id']} carries mixins ({len(mod['mixin_configs'])} config(s), "
                f"{mod['mixin_classes']} mixin class(es)): this bake applies entrypoints only, so those "
                f"mixins will not be applied")

    # the mod jars are copied into the engine, so the patcher finds them where the build runs
    shipped_dir = engine / "port" / "work" / version / "webmc-mods"
    shipped_dir.mkdir(parents=True, exist_ok=True)
    shipped = []
    for mod, jar in zip(mods, [jar for jar in mod_jars if jar.is_file()]):
        target = shipped_dir / jar.name
        shutil.copyfile(mods_dir / jar.name if mods_dir else jar, target)
        shipped.append(str(target))
        mod["shipped"] = str(target)

    tools_dir = engine / "port" / "tools" / "src" / "main" / "java" / "dev" / "gaius" / "tools"
    if not tools_dir.is_dir():
        raise SystemExit(f"{engine} does not look like a profile-based engine: no {tools_dir}")
    patcher = tools_dir / f"{PATCHER_CLASS}.java"
    # a named placeholder rather than %-formatting: the template is Java, and one stray percent sign in
    # it becomes a compile error forty-five minutes into a build
    patcher.write_text(PATCHER_JAVA.replace("__CLASS__", PATCHER_CLASS))
    log(f"  wrote {patcher.relative_to(engine)}")

    overrides = engine / "port" / "overrides" / "client" / "src" / "versions" / version / "java"
    hook = overrides / "webmc" / "baked" / "WebMcBakedMods.java"
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(hook_source(mods))
    log(f"  wrote {hook.relative_to(engine)} ({len(mods)} mod(s))")

    shim = SHIMS / "net" / "fabricmc" / "api" / "ClientModInitializer.java"
    if shim.is_file():
        shim_target = overrides / "net" / "fabricmc" / "api" / "ClientModInitializer.java"
        shim_target.parent.mkdir(parents=True, exist_ok=True)
        shim_target.write_text(shim.read_text())
        log(f"  wrote {shim_target.relative_to(engine)} (the interface a Fabric mod compiles against)")

    profile_path = engine / "port" / "versions" / f"{version}.json"
    if not profile_path.is_file():
        raise SystemExit(f"no profile at {profile_path} to add the patcher to")
    profile = json.loads(profile_path.read_text())
    patchers = [name for name in (profile.get("extraPatchers") or []) if name != PATCHER_CLASS]
    patchers.append(PATCHER_CLASS)
    profile["extraPatchers"] = patchers
    profile_path.write_text(json.dumps(profile, indent=1) + "\n")
    log(f"  {profile_path.relative_to(engine)}: extraPatchers = {patchers}")

    return {
        "version": version,
        "patcher": PATCHER_CLASS,
        "mods": mods,
        "mod_jars": shipped,
        "webmc_mods": ":".join(shipped),
        "hook": str(hook.relative_to(engine)),
        "with_mixins": [mod["id"] for mod in mods if mod["needs_mixins"]],
        "entrypoints": [mod["id"] for mod in mods if mod["entrypoint"]],
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--mods", action="append", default=[], help="a mod jar (repeatable)")
    parser.add_argument("--mods-dir", default=None, help="where those jars came from")
    parser.add_argument("--report", default=None)
    parser.add_argument("--print", action="store_true")
    args = parser.parse_args(argv)

    if not args.mods:
        print("nothing to bake: pass --mods")
        return 2
    report = bake(pathlib.Path(args.engine), args.version, [pathlib.Path(p) for p in args.mods],
                  pathlib.Path(args.mods_dir) if args.mods_dir else None)
    print(f"baked {len(report['mods'])} mod(s) into {args.version}: "
          f"entrypoints {', '.join(report['entrypoints']) or 'none'}"
          + (f"; mixins present in {', '.join(report['with_mixins'])} (not applied)" if report["with_mixins"] else ""))
    print(f"WEBMC_MODS={report['webmc_mods']}")
    if args.print:
        print(json.dumps(report, indent=1))
    if args.report:
        pathlib.Path(args.report).write_text(json.dumps(report, indent=1) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
