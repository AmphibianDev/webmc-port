#!/usr/bin/env python3
"""Write the LWJGL 3 natives that 1.21.11 asks for into the shim's JavaScript.

    python3 tools/lwjgl3_generate.py                 # write them into natives/webmc-lwjgl3.js
    python3 tools/lwjgl3_generate.py --check         # report what is still missing, change nothing

The members are not chosen here: they are measured (tools/lwjgl3_surface.py reads the client's own constant
pools and tools/lwjgl3_shapes.py reads the real declarations out of the LWJGL jars the client ships with). What
this file adds is the *translation* - each demanded member mapped to the browser API that does the same thing -
and it exists because most of them are mechanical: `glGenTextures` is createTexture plus a handle, `glBind…` is
bind…, `glTexParameteri` is texParameteri with the same constants. Writing those by hand, 195 times, is how a
typo becomes a black screen.

Three kinds of entry:

  * a table row, when the translation is mechanical (most of them);
  * hand-written code, when it is not: WebGL 2 has no direct state access, no uniform buffer objects, no
    fences and no base-vertex draws, so those are emulated, approximate, or refused out loud;
  * a deliberate refusal, when the honest thing is to say no: FreeType and OpenAL are turned *off* the way they
    are off on a machine that lacks them, so the client takes its own fallback path (stb_truetype for fonts, no
    sound at all) instead of walking into a shim that would pretend and then misbehave.

Anything in the generated block is replaced on the next run. Anything outside it is left alone.
"""

